  await publicPage.locator('.pc-price').filter({hasText:'₹2,100'}).waitFor()
  await publicPage.goto(publicBase+'/browser-test',{waitUntil:'domcontentloaded'})
  await publicPage.getByRole('heading',{name:'Updated page',exact:true}).waitFor()
  await publicPage.getByRole('heading',{name:'Preview works',exact:true}).waitFor()
  assert.equal((await publicPage.request.get(publicBase+'/browser-test')).status(),200)
  await page.getByRole('link',{name:'Customer activity',exact:true}).click()
  await page.getByRole('heading',{name:'Customer activity',exact:true}).waitFor()
  await publicPage.close()
  await page.getByRole('button',{name:'Sign out',exact:true}).click()
  await page.getByRole('heading',{name:'Admin sign in'}).waitFor()
