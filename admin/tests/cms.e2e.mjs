  await repo.put('orders','order_browser',{id:'order_browser',customerKey:keyFor('buyer@example.invalid'),plan:'Starter',amount:199000,status:'paid',createdAt:Date.now(),paidAt:Date.now(),testMode:false,billing:{email:'buyer@example.invalid',name:'Test Buyer'}})
