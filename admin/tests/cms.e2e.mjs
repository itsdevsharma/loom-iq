  process.env.MEDIA_STORAGE_PATH=path.join(dir,'media')
  const repo=fileRepository(path.join(dir,'state.json'))
  await repo.put('admins',keyFor('editor@example.invalid'),{email:'editor@example.invalid',passwordHash:await bcrypt.hash('test-password-only',4),roles:['superadmin']})
